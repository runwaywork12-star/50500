/** One-time best-effort snapshot for legacy orders; new orders always persist unit_cost at checkout. */
async function migrateLegacyOrderCosts(client: PoolClient) {
  const done = await client.query("SELECT 1 FROM app_meta WHERE key = 'legacy_order_cost_snapshot_v1'");
  if (done.rowCount) return;
  await client.query(`
    UPDATE order_items oi
       SET unit_cost = p.cost_price
      FROM products p
     WHERE oi.product_id = p.id AND oi.unit_cost = 0 AND p.cost_price > 0
  `);
  await client.query("INSERT INTO app_meta (key, value) VALUES ('legacy_order_cost_snapshot_v1', '1') ON CONFLICT (key) DO NOTHING");
}

async function init() {
  const client = await pool.connect();
  try {
    await client.query("SELECT pg_advisory_lock(50500)");
    for (const statement of DDL) {
      await client.query(statement);
    }
    const version = await client.query<{ value: string }>("SELECT value FROM app_meta WHERE key = 'seed_version'");
    if (version.rows[0]?.value !== SEED_VERSION) {
      const cats = await client.query<{ c: number }>("SELECT count(*)::int AS c FROM categories");
      const hasCatalog = (cats.rows[0]?.c ?? 0) > 0;
      if (hasCatalog && process.env.ALLOW_DEMO_CATALOG_RESET === "true" && process.env.NODE_ENV !== "production") {
        await resetCatalog(client);
      }
      // Existing catalogs are never wiped automatically. Seed only an empty database.
      if (!hasCatalog) await seedDatabase();
      await client.query(
        "INSERT INTO app_meta (key, value) VALUES ('seed_version', $1) ON CONFLICT (key) DO UPDATE SET value = excluded.value",
        [SEED_VERSION],
      );
    }
    await migrateVehicleDirectory(client);
    await migrateMatPhotos(client);
    await migrateOwnerSuppliedImages(client);
    await migrateAccessoryPhotos(client);
    await migrateAccessoryIllustrations(client);
    await seedSettings(client);
    await migrateLeatherMatStructure(client);
    await migrateCostPrice(client);
    await migrateLegacyOrderCosts(client);
  } finally {
    try {
      await client.query("SELECT pg_advisory_unlock(50500)");
    } catch {
      // ignore
    }
    client.release();
  }
}
