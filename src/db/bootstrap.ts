/** Bump when the demo catalogue changes; older catalogues are replaced automatically. */
export const SEED_VERSION = "7-clean-photos";

const g = globalThis as typeof globalThis & { __store50500Ready?: Promise<void> };

/**
 * Makes sure tables exist (idempotent DDL) and seeds / migrates the catalogue.
 * Runs once per server process.
 */
export function ensureDb(): Promise<void> {
  if (!g.__store50500Ready) {
    g.__store50500Ready = init().catch((error) => {
      g.__store50500Ready = undefined;
      throw error;
    });
  }
  return g.__store50500Ready;
}

async function resetCatalog(client: PoolClient) {
  await client.query("BEGIN");
  try {
    // Demo orders are regenerated by the seed; real orders keep their item snapshots.
    await client.query("DELETE FROM orders WHERE code = ANY($1::text[])", [DEMO_ORDER_CODES]);
    await client.query("DELETE FROM products");
    await client.query("DELETE FROM car_models");
    await client.query("DELETE FROM brands");
    await client.query("DELETE FROM categories");
    await client.query("COMMIT");
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  }
}

/** Adds the expanded make/model directory from the supplied catalog without creating demo products.
 * Existing admin-edited names, sort orders, products, prices and order history are never overwritten.
 */
async function migrateVehicleDirectory(client: PoolClient) {
  const done = await client.query("SELECT 1 FROM app_meta WHERE key = 'vehicle_directory_extensions_v1'");
  if (done.rowCount) return;

  await client.query("BEGIN");
  try {
    // Correct only two known legacy seed labels; never overwrite a later admin rename.
    await client.query("UPDATE brands SET name = 'دانگ فنگ' WHERE slug = 'dongfeng' AND name = 'دانگ فانگ'");
    await client.query("UPDATE brands SET name = 'BYD' WHERE slug = 'byd' AND name = 'بایدی'");
    for (const [brandIndex, entry] of VEHICLE_DIRECTORY_EXTENSIONS.entries()) {
      let found = await client.query<{ id: number }>("SELECT id FROM brands WHERE slug = $1 LIMIT 1", [entry.slug]);
      if (!found.rowCount) {
        await client.query(
          "INSERT INTO brands (slug, name, name_en, sort_order) VALUES ($1, $2, $3, $4) ON CONFLICT (slug) DO NOTHING",
          [entry.slug, entry.name, entry.nameEn, 100 + brandIndex],
        );
        found = await client.query<{ id: number }>("SELECT id FROM brands WHERE slug = $1 LIMIT 1", [entry.slug]);
      }
      const brandId = found.rows[0]?.id;
      if (!brandId) throw new Error(`Vehicle make could not be resolved: ${entry.slug}`);

      for (const [modelIndex, [modelSlug, modelName]] of entry.models.entries()) {
        const safeModelSlug = String(modelSlug).normalize("NFKD").toLowerCase().replace(/[^a-z0-9\u0600-\u06ff-]+/g, "-").replace(/^-+|-+$/g, "");
        if (!safeModelSlug || !modelName.trim()) continue;
        const slug = `${entry.slug}-${safeModelSlug}`.slice(0, 150);
        await client.query(
          `INSERT INTO car_models (brand_id, slug, name, full_name, sort_order)
           VALUES ($1, $2, $3, $4, $5)
           ON CONFLICT (slug) DO NOTHING`,
          [brandId, slug, modelName.trim(), `${entry.name} ${modelName.trim()}`, 100 + modelIndex],
        );
      }
    }

    await client.query(
      "INSERT INTO app_meta (key, value) VALUES ('vehicle_directory_extensions_v1', '1') ON CONFLICT (key) DO NOTHING",
    );
    await client.query("COMMIT");
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  }
}

/**
 * One-off, non-destructive: point every mat product (and the category cover) at the four
 * real-photo slots. Prices, stock and other admin edits are left untouched.
 */
async function migrateMatPhotos(client: PoolClient) {
  const done = await client.query("SELECT 1 FROM app_meta WHERE key = 'mat_photos_v1'");
  if (done.rowCount) return;
  const params = MAT_URLS.map((u) => JSON.stringify(u));
  const cat = "(SELECT id FROM categories WHERE slug = 'embroidered-leather')";
  await client.query(`UPDATE categories SET image = $1 WHERE slug = 'embroidered-leather'`, [MAT_URLS[0]]);
  await client.query(
    `UPDATE products SET images = (ARRAY[
        jsonb_build_array($1::text,$2::text,$3::text,$4::text),
        jsonb_build_array($2::text,$3::text,$4::text,$1::text),
        jsonb_build_array($3::text,$4::text,$1::text,$2::text),
        jsonb_build_array($4::text,$1::text,$2::text,$3::text)
      ])[(id % 4) + 1]
     WHERE category_id = ${cat}`,
    MAT_URLS,
  );
  void params;
  await client.query("INSERT INTO app_meta (key, value) VALUES ('mat_photos_v1', '1') ON CONFLICT (key) DO NOTHING");
}

/** Replaces unrelated stock photos on accessories without touching price, stock or orders. */
async function migrateAccessoryPhotos(client: PoolClient) {
  const done = await client.query("SELECT 1 FROM app_meta WHERE key = 'accessory_photos_v1'");
  if (done.rowCount) return;
  for (const [slug, image] of Object.entries(ACCESSORY_PHOTOS)) {
    await client.query(
      "UPDATE products SET images = $1::jsonb WHERE slug = $2",
      [JSON.stringify([image]), slug],
    );
  }
  await client.query(
    "UPDATE categories SET image = $1 WHERE slug = 'accessories'",
    [ACCESSORY_CATEGORY_PHOTO],
  );
  await client.query("INSERT INTO app_meta (key, value) VALUES ('accessory_photos_v1', '1') ON CONFLICT (key) DO NOTHING");
}

