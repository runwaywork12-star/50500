/** Installs the two owner-supplied default images once without touching orders or prices.
 * All vehicle mat products use the shared mat route until an admin uploads a per-product photo.
 * The one-time reset is intentional: the owner asked to use this single mat photo across the catalogue for now.
 */
async function migrateOwnerSuppliedImages(client: PoolClient) {
  const done = await client.query("SELECT 1 FROM app_meta WHERE key = 'owner_supplied_images_v1'");
  if (done.rowCount) return;

  const heroPath = path.join(process.cwd(), "public", "images", "hero-workshop-50500.png");
  const matPath = path.join(process.cwd(), "public", "images", "mat-default-50500.png");
  const [heroBytes, matBytes] = await Promise.all([readFile(heroPath), readFile(matPath)]);

  await client.query("BEGIN");
  try {
    const hero = await client.query<{ id: number }>(
      "INSERT INTO uploads (mime, data) VALUES ('image/png', $1) RETURNING id",
      [heroBytes.toString("base64")],
    );
    const mat = await client.query<{ id: number }>(
      "INSERT INTO uploads (mime, data) VALUES ('image/png', $1) RETURNING id",
      [matBytes.toString("base64")],
    );
    const heroId = hero.rows[0]?.id;
    const matId = mat.rows[0]?.id;
    if (!heroId || !matId) throw new Error("Unable to register owner-supplied default images");

    for (const key of ["hero", "hero-mobile"]) {
      await client.query(
        "INSERT INTO app_meta (key, value) VALUES ($1, $2) ON CONFLICT (key) DO UPDATE SET value = excluded.value",
        [`site_image:${key}`, String(heroId)],
      );
    }
    for (const key of ["mat", "mat-black-red", "mat-black-white", "mat-tan", "mat-brown"]) {
      await client.query(
        "INSERT INTO app_meta (key, value) VALUES ($1, $2) ON CONFLICT (key) DO UPDATE SET value = excluded.value",
        [`site_image:${key}`, String(matId)],
      );
    }

    // All current floor-mat products start with the same temporary owner-supplied image.
    // Product-level image upload replaces only that product's image array.
    await client.query(
      `UPDATE products p SET images = jsonb_build_array($1::text)
       FROM categories c WHERE p.category_id = c.id AND c.slug = 'embroidered-leather'`,
      [MAT_URLS[0]],
    );
    await client.query(
      "UPDATE categories SET image = $1 WHERE slug = 'embroidered-leather'",
      [MAT_URLS[0]],
    );
    await client.query("INSERT INTO app_meta (key, value) VALUES ('owner_supplied_images_v1', '1') ON CONFLICT (key) DO NOTHING");
    await client.query("COMMIT");
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  }
}

/** Seeds default site settings (texts, contact, hero, gateways) without overwriting edits. */
async function seedSettings(client: PoolClient) {
  const done = await client.query("SELECT 1 FROM app_meta WHERE key = 'settings_v1'");
  if (done.rowCount) return;
  for (const [key, value] of Object.entries(DEFAULT_SETTINGS)) {
    await client.query("INSERT INTO site_settings (key, value) VALUES ($1, $2) ON CONFLICT (key) DO NOTHING", [key, value]);
  }
  await client.query("INSERT INTO app_meta (key, value) VALUES ('settings_v1', '1') ON CONFLICT (key) DO NOTHING");
}

/** One-off, non-destructive correction of the leather-mat structure in existing catalogues. */
async function migrateLeatherMatStructure(client: PoolClient) {
  const done = await client.query("SELECT 1 FROM app_meta WHERE key = 'leather_mat_structure_v1'");
  if (done.rowCount) return;

  await client.query(`
    UPDATE products p
    SET specs = (
      SELECT COALESCE(jsonb_agg(
        CASE
          WHEN lower(COALESCE(item->>'label', '')) IN ('جنس رویه', 'جنس')
            THEN jsonb_build_object('label', 'جنس رویه', 'value', 'رویه چرمی')
          WHEN lower(COALESCE(item->>'label', '')) = 'ساختار'
            THEN jsonb_build_object('label', 'ساختار', 'value', '۴ لایه: رویه چرمی، فوم ۹ میلی‌متری، پارچه جودون و لایه زیرین')
          WHEN lower(COALESCE(item->>'label', '')) IN ('گلدوزی', 'دوخت')
            THEN jsonb_build_object('label', 'دوخت', 'value', 'دوخت ریزبافت')
          WHEN lower(COALESCE(item->>'label', '')) = 'طرح گلدوزی'
            THEN jsonb_build_object('label', 'جزئیات دوخت', 'value', 'دوخت ریزبافت')
          WHEN lower(COALESCE(item->>'label', '')) = 'مقاومت دمایی' THEN NULL
          ELSE item
        END ORDER BY ord
      ) FILTER (WHERE item IS NOT NULL AND lower(COALESCE(item->>'label', '')) <> 'مقاومت دمایی'), '[]'::jsonb)
      FROM jsonb_array_elements(p.specs) WITH ORDINALITY AS specs(item, ord)
    )
    FROM categories c
    WHERE p.category_id = c.id AND c.slug = 'embroidered-leather'
      AND jsonb_typeof(p.specs) = 'array'
  `);

  // Replace old seeded category copy only when it contains the incorrect materials claim.
  await client.query(`
    UPDATE categories
    SET description = 'رویه چرمی با دوخت ریزبافت، فوم ۹ میلی‌متری و پارچه جودون؛ ساختار چهارلایه کفپوش.'
    WHERE slug = 'embroidered-leather'
      AND (description ILIKE '%TPE%' OR description ILIKE '%XPE%' OR description ILIKE '%چرم نانو%')
  `);

  await client.query("INSERT INTO app_meta (key, value) VALUES ('leather_mat_structure_v1', '1') ON CONFLICT (key) DO NOTHING");
}

